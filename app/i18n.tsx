export type Language = "en" | "zh";
export type TextKey = keyof typeof english;
export const LanguageContext = createContext<Language>("en");

export function useLanguage() {
  const language = useContext(LanguageContext);
  const t = (key: TextKey, values: Record<string, string | number> = {}) => {
    const template = language === "en" ? english[key] : key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
  };
  return { language, t };
}
